#!/usr/bin/env bun
// Generates profile/README.md (the organization profile) from the live repository list.
// Rules: standard.toml [profile]. Usage: bun profile/generate.ts [--out profile/README.md] [--check] [--stats]
// Token: GH_TOKEN, GITHUB_TOKEN or `gh auth token`. Public data only; private and archived repositories are left out.
import { parseArgs } from "node:util";
import { dirname, join, resolve } from "node:path";

type Repo = {
  full_name: string;
  name: string;
  owner: { login: string };
  description: string | null;
  language: string | null;
  fork: boolean;
  private: boolean;
  archived: boolean;
  topics?: string[];
  homepage: string | null;
  html_url: string;
};
type Role = { id: string; title: string; blurb: string; repos?: string[]; patterns?: string[]; fallback_for_originals?: boolean };
type Family = { title: string; patterns: string[] };
type ProfileConfig = {
  output: string;
  owners: string[];
  include_private: boolean;
  include_archived: boolean;
  heading: string;
  tagline: string;
  roles: Role[];
  fork_families: Family[];
};

const root = resolve(dirname(import.meta.dir));
const { values: args } = parseArgs({
  options: { out: { type: "string" }, check: { type: "boolean" }, stats: { type: "boolean" } },
});

async function token(): Promise<string> {
  const env = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;
  if (env) return env;
  const p = Bun.spawnSync(["gh", "auth", "token"]);
  if (p.exitCode === 0) return p.stdout.toString().trim();
  throw new Error("no GitHub token: set GH_TOKEN or run gh auth login");
}

async function list(url: string, auth: string): Promise<Repo[]> {
  const out: Repo[] = [];
  for (let page = 1; ; page++) {
    const res = await fetch(`${url}${url.includes("?") ? "&" : "?"}per_page=100&page=${page}`, {
      headers: { authorization: `Bearer ${auth}`, accept: "application/vnd.github+json", "x-github-api-version": "2022-11-28" },
    });
    if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
    const rows = (await res.json()) as Repo[];
    out.push(...rows);
    if (rows.length < 100) return out;
  }
}

const config = (Bun.TOML.parse(await Bun.file(join(root, "standard.toml")).text()) as { profile: ProfileConfig }).profile;
const auth = await token();
const all: Repo[] = [];
for (const owner of config.owners) {
  const org = await fetch(`https://api.github.com/orgs/${owner}`, { headers: { authorization: `Bearer ${auth}` } });
  const url = org.ok ? `https://api.github.com/orgs/${owner}/repos?type=all` : `https://api.github.com/users/${owner}/repos?type=owner`;
  all.push(...(await list(url, auth)));
}

const visible = all.filter((r) => (config.include_private || !r.private) && (config.include_archived || !r.archived) && r.name !== ".github" && !/^aphrody-dev$/.test(r.name));
const originals = visible.filter((r) => !r.fork).sort((a, b) => a.name.localeCompare(b.name, "en"));
const forks = visible.filter((r) => r.fork).sort((a, b) => a.name.localeCompare(b.name, "en"));

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const short = (s: string | null, n = 170) => {
  const t = esc(s ?? "");
  if (!t) return "-";
  return t.length > n ? `${t.slice(0, n - 1).trimEnd()}…` : t;
};

function roleOf(r: Repo): Role {
  const topic = (r.topics ?? []).find((t) => t.startsWith("aphrody-"));
  const byTopic = topic && config.roles.find((x) => `aphrody-${x.id}` === topic);
  if (byTopic) return byTopic;
  for (const role of config.roles) {
    if (role.repos?.includes(r.full_name)) return role;
    if (role.patterns?.some((p) => new RegExp(p, "i").test(r.name))) return role;
  }
  return config.roles.find((x) => x.fallback_for_originals) ?? config.roles[config.roles.length - 1];
}

const familyRes = config.fork_families.map((f) => ({ title: f.title, res: f.patterns.map((p) => new RegExp(p, "i")) }));
function familyOf(r: Repo): string {
  for (const f of familyRes) if (f.res.some((re) => re.test(r.name))) return f.title;
  return "Other upstream forks";
}

const byRole = new Map<string, Repo[]>();
for (const r of originals) {
  const id = roleOf(r).id;
  byRole.set(id, [...(byRole.get(id) ?? []), r]);
}
const byFamily = new Map<string, Repo[]>();
for (const r of forks) {
  const f = familyOf(r);
  byFamily.set(f, [...(byFamily.get(f) ?? []), r]);
}

if (args.stats) {
  for (const [k, v] of byRole) console.log(`role ${k}: ${v.length}`);
  for (const [k, v] of byFamily) console.log(`family ${k}: ${v.length}`);
  console.log("other:", (byFamily.get("Other upstream forks") ?? []).map((r) => r.name).join(" "));
}

const link = (r: Repo) => `[${r.owner.login === "aphrody-labs" ? r.name : r.full_name}](${r.html_url})`;
const lines: string[] = [];
lines.push("<!-- generated by profile/generate.ts from the GitHub API; edit standard.toml [profile], not this file -->");
lines.push('<p align="center">');
lines.push('  <img alt="Aphrody" src="https://avatars.githubusercontent.com/u/335211382?v=4&s=200" width="100" height="100">');
lines.push("</p>");
lines.push("");
lines.push(`<h1 align="center">${config.heading}</h1>`);
lines.push("");
lines.push(`<p align="center">${config.tagline}</p>`);
lines.push("");
lines.push(
  `${originals.length} projects · ${forks.length} upstream forks · [Standard](https://github.com/aphrody-labs/.github/blob/main/STANDARD.md) · [Security](https://github.com/aphrody-labs/.github/blob/main/SECURITY.md) · [Contributing](https://github.com/aphrody-labs/.github/blob/main/CONTRIBUTING.md)`,
);
lines.push("");

for (const role of config.roles) {
  const rows = byRole.get(role.id) ?? [];
  if (!rows.length) continue;
  lines.push(`## ${role.title}`);
  lines.push("");
  lines.push(role.blurb);
  lines.push("");
  lines.push("| Project | Description | Language |");
  lines.push("| :-- | :-- | :-- |");
  for (const r of rows) lines.push(`| ${link(r)} | ${short(r.description)} | ${r.language ?? "-"} |`);
  lines.push("");
}

lines.push("## Forks");
lines.push("");
lines.push("Upstream forks kept for study, patching and vendoring, grouped by family. Each fork keeps its upstream license and README.");
lines.push("");
const order = [...config.fork_families.map((f) => f.title), "Other upstream forks"];
for (const title of order) {
  const rows = byFamily.get(title);
  if (!rows?.length) continue;
  lines.push("<details>");
  lines.push(`<summary><b>${title}</b> (${rows.length})</summary>`);
  lines.push("");
  lines.push(rows.map((r) => `[${r.name}](${r.html_url})`).join(" · "));
  lines.push("");
  lines.push("</details>");
  lines.push("");
}

lines.push("---");
lines.push("");
lines.push(
  "This page is generated from the live repository list by [profile/generate.ts](https://github.com/aphrody-labs/.github/blob/main/profile/generate.ts); roles and families are defined in [standard.toml](https://github.com/aphrody-labs/.github/blob/main/standard.toml). Private and archived repositories are left out.",
);
lines.push("");

const text = lines.join("\n");
const outPath = resolve(root, args.out ?? config.output);
if (args.check) {
  const cur = await Bun.file(outPath).text().catch(() => "");
  if (cur !== text) {
    console.error(`${outPath} is out of date`);
    process.exit(1);
  }
  console.log("up to date");
} else {
  await Bun.write(outPath, text);
  console.log(`wrote ${outPath}: ${originals.length} originals, ${forks.length} forks`);
}
